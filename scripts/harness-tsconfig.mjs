// Writes `tsconfig.harness.json`: the module paths the plugins are type-checked
// against, pointing into this machine's harness checkout and dsh-im-extras
// checkout (see `harness-root.mjs`). Same approach as dsh-im-extras: the
// location of those checkouts is a property of the machine, not of the
// repository, so the file is generated and never committed. Every package's
// `tsconfig.json` extends it next to `tsconfig.base.json`:
//
//     "extends": ["../../tsconfig.base.json", "../../tsconfig.harness.json"]
//
// Run it with `pnpm run harness` (`build`, `typecheck` and `test` do it for you).
import { existsSync, writeFileSync } from 'node:fs'
import { join, relative, resolve, sep } from 'node:path'

import { extrasRoot, harnessRoot, repoRoot } from './harness-root.mjs'

/** The harness specifiers the plugins import, and where their declarations live inside a built checkout. */
const HARNESS_PEERS = {
  '@deepseek-ai/cordis': 'vendor/cordis/lib/types/index.d.ts',
  // The Satori-derived IM packages live under `vendor/im/` on the mainline (`vendor/plugin-im-*` and
  // `vendor/satori-*` were the feat/im-automation layout).
  '@deepseek-ai/cordis-plugin-im-core': 'vendor/im/core/lib/types/index.d.ts',
  '@deepseek-ai/schemastery': 'vendor/schemastery/lib/types/index.d.ts',
  '@deepseek-ai/satori-element': 'vendor/im/element/lib/types/index.d.ts',
  '@deepseek-ai/dsh-im': 'packages/experimental/im/lib/types/index.d.ts',
  '@deepseek-ai/dsh-agent': 'packages/core/agent/lib/types/index.d.ts',
  '@deepseek-ai/dsh-client-connection': 'packages/client/connection/lib/types/index.d.ts',
  '@deepseek-ai/dsh-llm': 'packages/llm/llm/lib/types/index.d.ts',
  '@deepseek-ai/dsh-llm/assistant-stream': 'packages/llm/llm/lib/types/assistant-stream.d.ts',
  '@deepseek-ai/dsh-session': 'packages/core/session/lib/types/index.d.ts',
  '@deepseek-ai/dsh-storage-domain': 'packages/storage/storage-domain/lib/types/index.d.ts',
  '@deepseek-ai/dsh-system-prompt': 'packages/core/system-prompt/lib/types/index.d.ts',
  '@deepseek-ai/dsh-tools': 'packages/core/tools/lib/types/index.d.ts',
  // The browser halves (`src/client`) build against the GUI's own client packages.
  'react': 'node_modules/@types/react/index.d.ts',
  'react/jsx-runtime': 'node_modules/@types/react/jsx-runtime.d.ts',
  '@deepseek-ai/dsh-client-ui-primitives': 'packages/client/ui-primitives/lib/types/index.d.ts',
}

/**
 * dsh-im-extras packages whose public contract the plugins use, types only: their emitted declarations, so build
 * them first (`pnpm build` in the extras checkout). At runtime nothing is imported from them; the services are
 * reached through `ctx`.
 */
const EXTRAS_PEERS = {
  'dsh-im-session-tasks': 'packages/im-session-tasks/dist/index.d.ts',
}

/** Specifiers pinned to this workspace's own copy (one zod for the whole program, as deployed). */
const WORKSPACE_PEERS = {
  zod: 'node_modules/zod/index.d.ts',
}

function toConfigPath(absolute) {
  const path = relative(repoRoot, absolute).split(sep).join('/')
  return path.startsWith('.') ? path : `./${path}`
}

const harness = harnessRoot()
const extras = extrasRoot()
const paths = {}
const missing = []
for (const [table, root] of [[HARNESS_PEERS, harness], [EXTRAS_PEERS, extras], [WORKSPACE_PEERS, repoRoot]]) {
  for (const [specifier, entry] of Object.entries(table)) {
    const absolute = resolve(root, entry)
    if (!existsSync(absolute)) missing.push(`${specifier} → ${absolute}`)
    paths[specifier] = [toConfigPath(absolute)]
  }
}
if (missing.length > 0) {
  throw new Error(`these declarations are missing (build the harness, build dsh-im-extras, run pnpm install):\n  ${missing.join('\n  ')}`)
}

const config = {
  '//': [
    'generated by scripts/harness-tsconfig.mjs — do not edit, do not commit',
    'set DSH_HARNESS_ROOT / DSH_IM_EXTRAS_ROOT (or .harness-root / .extras-root) to point at other checkouts',
  ],
  compilerOptions: {
    typeRoots: [toConfigPath(join(repoRoot, 'node_modules', '@types'))],
    paths,
  },
}
writeFileSync(join(repoRoot, 'tsconfig.harness.json'), `${JSON.stringify(config, null, 2)}\n`)
console.log(`tsconfig.harness.json: ${Object.keys(paths).length} peers (harness ${harness}, extras ${extras})`)
